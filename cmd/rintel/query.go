// Every result type here is both the CLI --format json output and the MCP structured output.

type ScanInfo struct {
	ID         int64  `json:"id"`
	Commit     string `json:"commit"`
	Dirty      bool   `json:"dirty"`
	Stale      bool   `json:"stale" jsonschema:"true when the working tree changed after this scan; call scan_repository to refresh"`
	StaleFiles int    `json:"stale_files"`
	ScannedAt  string `json:"scanned_at"`
}

type Location struct {
	File      string `json:"file"`
	StartLine int    `json:"start_line"`
	EndLine   int    `json:"end_line,omitempty"`
}

type Symbol struct {
	ID        string    `json:"id"`
	Type      string    `json:"type"`
	Module    string    `json:"module,omitempty"`
	External  bool      `json:"external,omitempty"`
	Kind      string    `json:"kind,omitempty" jsonschema:"for classes: class, interface, enum, record; for Go: struct, interface, type, or file (the package-level declarations of one file)"`
	Synthetic string    `json:"synthetic,omitempty" jsonschema:"set when the symbol has no declaration in the source: lombok (generated by a Lombok annotation) or implicit (default constructor or record accessor)"`
	Location  *Location `json:"location,omitempty"`
}

type Edge struct {
	From         string    `json:"from"`
	To           string    `json:"to"`
	Via          string    `json:"via,omitempty"`
	Relation     string    `json:"relation"`
	Evidence     string    `json:"evidence" jsonschema:"declared, resolved or heuristic"`
	Rule         string    `json:"rule,omitempty"`
	At           *Location `json:"at,omitempty"`
	Depth        int       `json:"depth"`
	PathEvidence string    `json:"path_evidence" jsonschema:"weakest evidence on the path from the root symbol to this edge"`
}

type Page struct {
	Truncated  bool   `json:"truncated"`
	NextCursor string `json:"next_cursor,omitempty"`
}

var errNoScan = errors.New("no scan yet: run `rintel scan` (or the scan_repository tool)")

type Q struct {
	root string
	db   *sql.DB
}

func (q *Q) scanInfo() (ScanInfo, error) {
	var s ScanInfo
	var madeBy string
	err := q.db.QueryRow(`SELECT id, commit_sha, dirty, finished_at, COALESCE(adapter_version,'') FROM scans ORDER BY id DESC LIMIT 1`).Scan(&s.ID, &s.Commit, &s.Dirty, &s.ScannedAt, &madeBy)
	if errors.Is(err, sql.ErrNoRows) {
		return s, errNoScan
	}
	if err != nil {
		return s, err
	}
	// staleness by mtime+size only: cheap enough to run on every query
	type stat struct{ mtime, size int64 }
	known := map[string]stat{}
	rows, err := q.db.Query(`SELECT path, mtime, size FROM files WHERE scan_id=?`, s.ID)
	if err != nil {
		return s, err
	}
	for rows.Next() {
		var p string
		var st stat
		rows.Scan(&p, &st.mtime, &st.size)
		known[p] = st
	}
	rows.Close()
	cfg := loadConfig(q.root)
	walk(q.root, func(rel string, info fs.FileInfo) error {
		if cfg.excluded(rel) {
			return nil
		}
		if st, ok := known[rel]; !ok || st.mtime != info.ModTime().UnixNano() || st.size != info.Size() {
			if ok || info.Size() <= maxFileSize {
				s.StaleFiles++
			}
		}
		delete(known, rel)
		return nil
	})
	s.StaleFiles += len(known)
	current, _, _ := scanVersion(q.root)
	s.Stale = s.StaleFiles > 0 || s.Commit != gitOut(q.root, "rev-parse", "HEAD") || madeBy != current // also after rintel itself was upgraded
	return s, nil
}

func page(limit int, cursor string) (int, int) {
	if limit <= 0 || limit > 200 {
		limit = 50
	}
	off, _ := strconv.Atoi(cursor)
	return limit, max(off, 0)
}

func (p *Page) set(more bool, limit, off int) {
	if more {
		p.Truncated, p.NextCursor = true, strconv.Itoa(off+limit)
	}
}

const symCols = `id, type, COALESCE(module,''), external, COALESCE(file,''), COALESCE(l1,0), COALESCE(l2,0), COALESCE(json_extract(attrs,'$.synthetic'),''), COALESCE(json_extract(attrs,'$.kind'),'')`

func scanSym(rows interface{ Scan(...any) error }) (Symbol, error) {
	var s Symbol
	var file string
	var l1, l2 int
	err := rows.Scan(&s.ID, &s.Type, &s.Module, &s.External, &file, &l1, &l2, &s.Synthetic, &s.Kind)
	if file != "" {
		s.Location = &Location{file, l1, l2}
	}
	return s, err
}

var likeEscaper = strings.NewReplacer(`\`, `\\`, `%`, `\%`, `_`, `\_`)

// ---- search_symbols ----

type SearchResult struct {
	Scan    ScanInfo `json:"scan"`
	Symbols []Symbol `json:"symbols"`
	Page
}

// shortcut: substring LIKE instead of FTS5; fine up to a few hundred thousand symbols, switch when search p95 exceeds the 200ms budget.
func (q *Q) Search(query, kind, module string, limit int, cursor string) (*SearchResult, error) {
	si, err := q.scanInfo()
	if err != nil {
		return nil, err
	}
	limit, off := page(limit, cursor)
	where, args := `scan_id=? AND external=0 AND fqn LIKE ? ESCAPE '\'`, []any{si.ID, "%" + likeEscaper.Replace(query) + "%"}
	if kind != "" {
		where, args = where+" AND type=?", append(args, kind)
	}
	if module != "" {
		where, args = where+" AND module=?", append(args, module)
	}
	rows, err := q.db.Query(`SELECT `+symCols+` FROM symbols WHERE `+where+` ORDER BY (lower(name)=lower(?)) DESC, (type='class') DESC, (json_extract(attrs,'$.synthetic') IS NOT NULL), length(name), fqn, id LIMIT ? OFFSET ?`,
		append(args, query, limit+1, off)...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	r := &SearchResult{Scan: si, Symbols: []Symbol{}}
	for rows.Next() {
		s, err := scanSym(rows)
		if err != nil {
			return nil, err
		}
		r.Symbols = append(r.Symbols, s)
	}
	if len(r.Symbols) > limit {
		r.Symbols = r.Symbols[:limit]
		r.set(true, limit, off)
	}
	return r, rows.Err()
}

type notFoundError struct {
	Ref   string
	Hints []string // symbol IDs
}

func (e *notFoundError) Error() string {
	if len(e.Hints) > 0 {
		return fmt.Sprintf("symbol not found: %s. Did you mean: %s", e.Ref, strings.Join(e.Hints, ", "))
	}
	return fmt.Sprintf("symbol not found: %s (try search_symbols)", e.Ref)
}

// resolve turns a user reference into symbol IDs. Accepted forms: a full ID, an FQN, a dotted suffix
// (UserService.createUser), and whatever the text output prints (UserService.createUser(String), new User(String)).
func (q *Q) resolve(scan int64, ref string) ([]string, error) {
	if len(ref) > 1000 { // no symbol is this long; a pattern built from it would only strain the database
		return nil, &notFoundError{Ref: ref[:60] + "…"}
	}
	name, sig := strings.TrimSpace(ref), ""
	if i := strings.Index(name, "("); i >= 0 {
		name, sig = name[:i], strings.ReplaceAll(name[i:], " ", "")
	}
	if strings.HasPrefix(name, "new ") {
		name = strings.TrimSpace(name[4:]) + ".<init>"
	}
	name = strings.Replace(name[strings.Index(name, ":")+1:], "#", ".", 1)
	if name == "" {
		return nil, &notFoundError{Ref: ref}
	}
	// a suffix may start after a dot (Java packages, members) or a slash (Go import paths: web.Server.handle)
	rows, err := q.db.Query(`SELECT id, fqn FROM symbols WHERE scan_id=? AND (fqn=? OR fqn LIKE ? ESCAPE '\' OR fqn LIKE ? ESCAPE '\') ORDER BY external, id LIMIT 1000`,
		scan, name, "%."+likeEscaper.Replace(name), "%/"+likeEscaper.Replace(name))
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var exact, suffix []string
	for rows.Next() {
		var id, fqn string
		rows.Scan(&id, &fqn)
		if sig != "" && !strings.HasSuffix(id, sig) {
			continue
		}
		// LIKE ignores case; Java names do not (OrderFacade the class vs orderFacade() the factory method)
		if fqn == name {
			exact = append(exact, id)
		} else if strings.HasSuffix(fqn, "."+name) || strings.HasSuffix(fqn, "/"+name) {
			suffix = append(suffix, id)
		}
	}
	ids := exact
	if len(ids) == 0 {
		ids = suffix
	}
	if len(ids) > 20 {
		ids = ids[:20]
	}
	if len(ids) > 0 {
		return ids, nil
	}
	// Suggest by the last name segment: an empty answer teaches nothing.
	last := name[strings.LastIndex(name, ".")+1:]
	nf := &notFoundError{Ref: ref}
	hint := func(where string, arg any) {
		rows, err := q.db.Query(`SELECT id FROM symbols WHERE scan_id=? AND external=0 AND `+where+` ORDER BY (type='class') DESC, length(fqn), id LIMIT 5`, scan, arg)
		if err != nil {
			return
		}
		defer rows.Close()
		for rows.Next() {
			var id string
			rows.Scan(&id)
			nf.Hints = append(nf.Hints, id)
		}
	}
	hint(`name LIKE ? ESCAPE '\'`, "%"+likeEscaper.Replace(last)+"%")
	if len(nf.Hints) == 0 { // a typo: closest declared name within two edits
		best, bestDist := "", 3
		if rows, err := q.db.Query(`SELECT DISTINCT name FROM symbols WHERE scan_id=? AND external=0 AND abs(length(name)-?)<=2`, scan, len(last)); err == nil {
			for rows.Next() {
				var n string
				rows.Scan(&n)
				if d := editDistance(strings.ToLower(n), strings.ToLower(last)); d < bestDist {
					best, bestDist = n, d
				}
			}
			rows.Close()
		}
		if best != "" {
			hint(`name=?`, best)
		}
	}
	return nil, nf
}

func editDistance(a, b string) int {
	prev := make([]int, len(b)+1)
	for j := range prev {
		prev[j] = j
	}
	for i := 1; i <= len(a); i++ {
		cur := make([]int, len(b)+1)
		cur[0] = i
		for j := 1; j <= len(b); j++ {
			cost := 1
			if a[i-1] == b[j-1] {
				cost = 0
			}
			cur[j] = min(prev[j]+1, cur[j-1]+1, prev[j-1]+cost)
		}
		prev = cur
	}
	return prev[len(b)]
}

// ---- get_symbol ----

type SymbolResult struct {
	Scan            ScanInfo       `json:"scan"`
	Symbol          Symbol         `json:"symbol"`
	Incoming        map[string]int `json:"incoming" jsonschema:"number of edges pointing at this symbol, by relation"`
	Outgoing        map[string]int `json:"outgoing" jsonschema:"number of edges leaving this symbol, by relation"`
	UnresolvedCount int            `json:"unresolved_count" jsonschema:"references inside this symbol that analysis could not resolve"`
}

func (q *Q) GetSymbol(ref string) (*SymbolResult, error) {
	si, err := q.scanInfo()
	if err != nil {
		return nil, err
	}
	ids, err := q.resolve(si.ID, ref)
	if err != nil {
		return nil, err
	}
	if len(ids) > 1 {
		return nil, fmt.Errorf("ambiguous symbol %q, candidates: %s", ref, strings.Join(ids, ", "))
	}
	r := &SymbolResult{Scan: si, Incoming: map[string]int{}, Outgoing: map[string]int{}}
	if r.Symbol, err = scanSym(q.db.QueryRow(`SELECT `+symCols+` FROM symbols WHERE scan_id=? AND id=?`, si.ID, ids[0])); err != nil {
		return nil, err
	}
	for col, m := range map[string]map[string]int{"dst": r.Incoming, "src": r.Outgoing} {
		rows, err := q.db.Query(`SELECT relation, COUNT(*) FROM dependencies WHERE scan_id=? AND `+col+`=? GROUP BY relation`, si.ID, ids[0])
		if err != nil {
			return nil, err
		}
		for rows.Next() {
			var rel string
			var n int
			rows.Scan(&rel, &n)
			m[rel] = n
		}
		rows.Close()
	}
	q.db.QueryRow(`SELECT COUNT(*) FROM unresolved_refs WHERE scan_id=? AND src=? AND reason<>'missing-type'`, si.ID, ids[0]).Scan(&r.UnresolvedCount)
	return r, nil
}

// symbol returns what is known about one ID; the zero Symbol if it is not in the scan.
func (q *Q) symbol(scan int64, id string) Symbol {
	s, _ := scanSym(q.db.QueryRow(`SELECT `+symCols+` FROM symbols WHERE scan_id=? AND id=?`, scan, id))
	return s
}

// ---- get_neighbors ----

type NeighborsResult struct {
	Scan            ScanInfo `json:"scan"`
	Direction       string   `json:"direction"`
	Roots           []string `json:"roots"`
	ExpandedFrom    []string `json:"expanded_from,omitempty" jsonschema:"classes whose methods and constructors were used as roots, because a class itself is never called"`
	Edges           []Edge   `json:"edges"`
	UnresolvedCount int      `json:"unresolved_count" jsonschema:"unresolved references inside the root symbols; a non-zero value means outgoing edges may be incomplete"`
	Page
}

var evidenceRank = map[string]int{"declared": 0, "resolved": 1, "heuristic": 2}

func (q *Q) Neighbors(ref, direction string, depth int, relation string, limit int, cursor string) (*NeighborsResult, error) {
	si, err := q.scanInfo()
	if err != nil {
		return nil, err
	}
	roots, err := q.resolve(si.ID, ref)
	if err != nil {
		return nil, err
	}
	if direction != "in" && direction != "out" {
		return nil, errors.New(`direction must be "in" or "out"`)
	}
	depth = min(max(depth, 1), 3)
	var expanded []string
	if relation == "calls" { // "who calls this class" means: who calls any of its members
		var out []string
		for _, id := range roots {
			var members []string
			if rows, err := q.db.Query(`SELECT m.id FROM symbols c JOIN symbols m ON m.scan_id=c.scan_id AND m.parent=c.id AND m.type IN ('method','constructor')
				WHERE c.scan_id=? AND c.id=? AND c.type='class' ORDER BY m.id LIMIT 300`, si.ID, id); err == nil {
				for rows.Next() {
					var m string
					rows.Scan(&m)
					members = append(members, m)
				}
				rows.Close()
			}
			if len(members) > 0 {
				expanded = append(expanded, id)
				out = append(out, members...)
			} else {
				out = append(out, id)
			}
		}
		roots = out
	}
	limit, off := page(limit, cursor)
	near, far := "src", "dst"
	if direction == "in" {
		near, far = far, near
	}
	stmt, err := q.db.Prepare(`SELECT src, dst, via, relation, evidence_level, COALESCE(rule,''), COALESCE(file,''), COALESCE(line,0)
		FROM dependencies WHERE scan_id=? AND ` + near + `=? AND (?='' OR relation=?) ORDER BY file, line, ` + far + `, relation`)
	if err != nil {
		return nil, err
	}
	defer stmt.Close()
	r := &NeighborsResult{Scan: si, Direction: direction, Roots: roots, ExpandedFrom: expanded, Edges: []Edge{}}
	pathEv := map[string]string{}
	for _, id := range roots {
		pathEv[id] = "declared"
	}
	const maxEdges = 5000 // bounds work on hub symbols
	for d, frontier := 1, roots; d <= depth && len(frontier) > 0 && len(r.Edges) < maxEdges; d++ {
		var next []string
		for _, node := range frontier {
			rows, err := stmt.Query(si.ID, node, relation, relation)
			if err != nil {
				return nil, err
			}
			for rows.Next() {
				e := Edge{Depth: d}
				var file string
				var line int
				rows.Scan(&e.From, &e.To, &e.Via, &e.Relation, &e.Evidence, &e.Rule, &file, &line)
				if file != "" {
					e.At = &Location{File: file, StartLine: line}
				}
				// evidence only degrades along a path
				e.PathEvidence = pathEv[node]
				if evidenceRank[e.Evidence] > evidenceRank[e.PathEvidence] {
					e.PathEvidence = e.Evidence
				}
				other := e.To
				if direction == "in" {
					other = e.From
				}
				if _, seen := pathEv[other]; !seen {
					pathEv[other] = e.PathEvidence
					next = append(next, other)
				}
				r.Edges = append(r.Edges, e)
			}
			rows.Close()
		}
		sort.Strings(next)
		frontier = next
	}
	for _, id := range roots {
		var n int
		q.db.QueryRow(`SELECT COUNT(*) FROM unresolved_refs WHERE scan_id=? AND src=? AND reason<>'missing-type'`, si.ID, id).Scan(&n)
		r.UnresolvedCount += n
	}
	total := len(r.Edges)
	r.Edges = r.Edges[min(off, total):min(off+limit, total)]
	r.set(total > off+limit, limit, off)
	return r, nil
}

// ---- get_api_spec ----

type Endpoint struct {
	Method   string    `json:"method"`
	Path     string    `json:"path"`
	Handler  string    `json:"handler"`
	Evidence string    `json:"evidence"`
	Location *Location `json:"location,omitempty"`
}

type APIResult struct {
	Scan      ScanInfo   `json:"scan"`
	Endpoints []Endpoint `json:"endpoints"`
	Page
}

func (q *Q) APISpec(prefix string, limit int, cursor string) (*APIResult, error) {
	si, err := q.scanInfo()
	if err != nil {
		return nil, err
	}
	limit, off := page(limit, cursor)
	if prefix != "" && !strings.HasPrefix(prefix, "/") {
		prefix = "/" + prefix
	}
	// where the route is registered if the adapter saw that, else where the handler is declared
	rows, err := q.db.Query(`SELECT e.method, e.path, e.handler, e.evidence_level, COALESCE(e.file,s.file,''), COALESCE(e.line,s.l1,0), CASE WHEN e.file IS NULL THEN COALESCE(s.l2,0) ELSE 0 END
		FROM api_endpoints e LEFT JOIN symbols s ON s.scan_id=e.scan_id AND s.id=e.handler
		WHERE e.scan_id=? AND e.path LIKE ? ESCAPE '\' ORDER BY e.path, e.method, e.handler LIMIT ? OFFSET ?`,
		si.ID, likeEscaper.Replace(prefix)+"%", limit+1, off)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	r := &APIResult{Scan: si, Endpoints: []Endpoint{}}
	for rows.Next() {
		var e Endpoint
		var file string
		var l1, l2 int
		rows.Scan(&e.Method, &e.Path, &e.Handler, &e.Evidence, &file, &l1, &l2)
		if file != "" {
			e.Location = &Location{file, l1, l2}
		}
		r.Endpoints = append(r.Endpoints, e)
	}
	if len(r.Endpoints) > limit {
		r.Endpoints = r.Endpoints[:limit]
		r.set(true, limit, off)
	}
	return r, rows.Err()
}

// ---- get_overview / stats ----

type Overview struct {
	Scan            ScanInfo       `json:"scan"`
	Modules         map[string]int `json:"modules" jsonschema:"analyzed source files per module"`
	Languages       map[string]int `json:"languages" jsonschema:"analyzed source files per language"`
	ExcludedFiles   map[string]int `json:"excluded_files" jsonschema:"files in languages that are NOT analyzed; the graph has holes where these are used"`
	Symbols         int            `json:"symbols"`
	Endpoints       int            `json:"endpoints"`
	Edges           map[string]int `json:"edges" jsonschema:"edge count by evidence level"`
	ResolvedCalls   int            `json:"resolved_calls"`
	UnresolvedCalls int            `json:"unresolved_calls" jsonschema:"call sites analysis could not resolve; callers of some symbols may be missing"`
	ResolutionRate  float64        `json:"resolution_rate" jsonschema:"resolved call references / all call references (0..1)"`
	ClasspathJars   int            `json:"classpath_jars"`
	MissingPackages []string       `json:"missing_packages" jsonschema:"imported Java packages that no local jar provides; build the project once to fetch them"`
	Warnings        []string       `json:"warnings" jsonschema:"languages found but not analyzed on this machine, and why"`
	Unresolved      map[string]int `json:"unresolved" jsonschema:"unresolved references by reason"`
}

func (q *Q) Overview() (*Overview, error) {
	si, err := q.scanInfo()
	if err != nil {
		return nil, err
	}
	o := &Overview{Scan: si, Modules: map[string]int{}, Languages: map[string]int{}, ExcludedFiles: map[string]int{}, Edges: map[string]int{}, Unresolved: map[string]int{}}
	group := func(m map[string]int, query string) error {
		rows, err := q.db.Query(query, si.ID)
		if err != nil {
			return err
		}
		defer rows.Close()
		for rows.Next() {
			var k string
			var n int
			rows.Scan(&k, &n)
			m[k] = n
		}
		return rows.Err()
	}
	for m, query := range map[*map[string]int]string{
		&o.Modules:       `SELECT module, COUNT(*) FROM files WHERE scan_id=? AND metrics IS NOT NULL GROUP BY 1`,
		&o.Languages:     `SELECT language, COUNT(*) FROM files WHERE scan_id=? AND metrics IS NOT NULL GROUP BY 1`,
		&o.ExcludedFiles: `SELECT language, COUNT(*) FROM files WHERE scan_id=? AND metrics IS NULL AND language<>'build' GROUP BY 1`,
		&o.Edges:         `SELECT evidence_level, COUNT(*) FROM dependencies WHERE scan_id=? GROUP BY 1`,
		&o.Unresolved:    `SELECT reason, COUNT(*) FROM unresolved_refs WHERE scan_id=? GROUP BY 1`,
	} {
		if err := group(*m, query); err != nil {
			return nil, err
		}
	}
	var calls, unresolved int
	q.db.QueryRow(`SELECT COUNT(*) FROM symbols WHERE scan_id=? AND external=0`, si.ID).Scan(&o.Symbols)
	q.db.QueryRow(`SELECT COUNT(*) FROM api_endpoints WHERE scan_id=?`, si.ID).Scan(&o.Endpoints)
	q.db.QueryRow(`SELECT COUNT(*) FROM dependencies WHERE scan_id=? AND origin='adapter' AND relation='calls'`, si.ID).Scan(&calls)
	// missing-type records are unresolved type names, not calls: they stay out of the call resolution rate
	q.db.QueryRow(`SELECT COUNT(*) FROM unresolved_refs WHERE scan_id=? AND reason<>'missing-type'`, si.ID).Scan(&unresolved)
	o.ResolvedCalls, o.UnresolvedCalls = calls, unresolved
	var stats string
	q.db.QueryRow(`SELECT COALESCE(stats_json,'{}') FROM scans WHERE id=?`, si.ID).Scan(&stats)
	var sr ScanResult
	json.Unmarshal([]byte(stats), &sr)
	o.ClasspathJars = sr.Classpath
	if o.MissingPackages = sr.MissingPackages; o.MissingPackages == nil {
		o.MissingPackages = []string{}
	}
	if o.Warnings = sr.Warnings; o.Warnings == nil {
		o.Warnings = []string{}
	}
	if calls+unresolved > 0 {
		o.ResolutionRate = float64(calls) / float64(calls+unresolved)
	}
	return o, nil
}
